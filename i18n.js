(function () {
  var KEY = 'cordel2-lang';
  var LOCALES = { pt: 'pt-BR', en: 'en', zh: 'zh-Hans' };
  var dict = window.I18N_STRINGS || {};
  var originals = null;

  function nodes() { return document.querySelectorAll('[data-i18n]'); }

  function snapshot() {
    originals = new Map();
    nodes().forEach(function (el) { originals.set(el, el.innerHTML); });
  }

  function apply(lang) {
    if (!originals) snapshot();
    var table = lang === 'pt' ? null : dict[lang];
    nodes().forEach(function (el) {
      var k = el.getAttribute('data-i18n');
      var v = table && table[k];
      el.innerHTML = typeof v === 'string' ? v : originals.get(el);
    });

    document.documentElement.lang = LOCALES[lang] || 'pt-BR';

    var desc = document.querySelector('meta[name="description"]');
    if (desc) {
      var dk = table && table['meta.description'];
      if (!desc.dataset.pt) desc.dataset.pt = desc.getAttribute('content');
      desc.setAttribute('content', dk || desc.dataset.pt);
    }

    document.querySelectorAll('.lang-switch button').forEach(function (b) {
      b.setAttribute('aria-pressed', String(b.dataset.lang === lang));
    });

    try { localStorage.setItem(KEY, lang); } catch (e) { /* modo privado */ }
  }

  function initial() {
    var saved;
    try { saved = localStorage.getItem(KEY); } catch (e) { saved = null; }
    if (saved && LOCALES[saved]) return saved;
    var nav = (navigator.language || 'pt').toLowerCase();
    if (nav.indexOf('zh') === 0) return 'zh';
    if (nav.indexOf('en') === 0) return 'en';
    return 'pt';
  }

  function start() {
    snapshot();
    document.querySelectorAll('.lang-switch button').forEach(function (b) {
      b.addEventListener('click', function () { apply(b.dataset.lang); });
    });
    apply(initial());
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', start);
  } else {
    start();
  }
})();
